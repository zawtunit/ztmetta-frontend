import { PGlite } from '@electric-sql/pglite';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const db = new PGlite();
const adminId = '00000000-0000-4000-8000-000000000001';
const otherId = '00000000-0000-4000-8000-000000000002';
try {
  // Supabase supplies these roles and auth functions in production.
  await db.exec(`create role anon; create role authenticated; create schema auth;
    create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql stable as $$
      select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid;
    $$;
    grant usage on schema auth to anon, authenticated;
    grant execute on function auth.uid() to anon, authenticated;
    insert into auth.users(id) values ('${adminId}'), ('${otherId}');`);
  await db.exec(await readFile(new URL('../supabase/migrations/20261116000100_chanmyay_shared.sql', import.meta.url), 'utf8'));
  await db.query('insert into public.cm_administrators(user_id) values ($1)', [adminId]);
  await assert.rejects(db.query('insert into public.cm_administrators(id,user_id) values (2,$1)', [otherId]));
  const offering = { id:'10000000-0000-4000-8000-000000000001', name:'Test donor A', phone:'PRIVATE-TEST-ONLY', dedication:'Test dedication', start_date:'2026-11-15',end_date:'2026-11-17',categories:['lunch'],status:'Approved' };
  const role = async (name, id='') => { await db.exec(`reset role; set role ${name};`); await db.query("select set_config('request.jwt.claim.sub', $1, false)", [id]); };
  const save = async (value, version=null) => (await db.query('select public.cm_save_offering($1::jsonb,$2::integer) as value',[JSON.stringify(value),version])).rows[0].value;
  const display = async (date) => (await db.query('select public.cm_tv_display($1::date) as value',[date])).rows[0].value;
  await role('anon');
  await assert.rejects(save(offering), /permission denied/);
  await assert.rejects(db.query('select phone from public.cm_offerings'), /permission denied/);
  await assert.rejects(db.query('select * from cm_private.audit_log'), /permission denied/);
  await role('authenticated', otherId);
  assert.equal((await db.query('select public.cm_is_admin() as value')).rows[0].value,false);
  assert.equal((await db.query('select * from public.cm_offerings')).rows.length,0);
  await assert.rejects(save(offering), /Administrator login/);
  await assert.rejects(db.query('update public.cm_offerings set name = $1',['intruder']), /permission denied/);
  await role('authenticated', adminId);
  assert.equal((await save(offering)).version,1);
  const changed=await save({...offering,name:'Test donor B'},1);
  assert.equal(changed.version,2);
  await assert.rejects(save({...offering,name:'Stale edit'},1), /changed on another device/);
  await assert.rejects(save({...offering,id:'10000000-0000-4000-8000-000000000003',end_date:'2026-11-01'}), /check constraint/);
  await assert.rejects(save({...offering,id:'10000000-0000-4000-8000-000000000004',categories:['invalid']}), /check constraint/);
  await save({...offering,id:'10000000-0000-4000-8000-000000000005',name:'Pending test donor',status:'Pending'});
  await save({...offering,id:'10000000-0000-4000-8000-000000000006',name:'Cancelled test donor',status:'Cancelled'});
  await db.query('select public.cm_save_display_settings($1,1)', ['နှစ်သစ်ကူး အလှူ']);
  await assert.rejects(db.query('select public.cm_save_display_settings($1,1)', ['Stale title']), /changed on another device/);
  const newImport={...offering,id:'10000000-0000-4000-8000-000000000007'};
  assert.equal((await db.query('select public.cm_import_offerings($1::jsonb) as value',[JSON.stringify([offering,newImport])])).rows[0].value,1);
  assert.equal((await db.query('select public.cm_import_offerings($1::jsonb) as value',[JSON.stringify([offering,newImport])])).rows[0].value,0);
  await role('anon');
  const publicDisplay=await display('2026-11-16');
  assert.equal(publicDisplay.event_name,'နှစ်သစ်ကူး အလှူ');
  assert.equal(publicDisplay.donors.length,2);
  assert.ok(publicDisplay.donors.every(value=>value.status==='Approved'));
  assert.ok(!JSON.stringify(publicDisplay).includes('PRIVATE-TEST-ONLY'));
  assert.ok(publicDisplay.donors.every(value=>!('phone' in value) && !('version' in value)));
  assert.equal((await display('2026-11-18')).donors.length,0);
  assert.equal((await display('2026-11-15')).donors.length,2);
  assert.equal((await display('2026-11-17')).donors.length,2);
  await assert.rejects(db.query('select public.cm_save_display_settings($1,2)', ['Anonymous title']), /permission denied/);
  await role('postgres');
  assert.equal((await db.query('select name from public.cm_offerings where id=$1',[offering.id])).rows[0].name,'Test donor B');
  assert.ok((await db.query('select count(*)::integer as count from cm_private.audit_log')).rows[0].count>=6);
  console.log('Passed: single administrator, anonymous/other-user restrictions, public phone exclusion, approval/date filters, event title, optimistic concurrency, validation, idempotent import and change history.');
} finally { await db.close(); }
